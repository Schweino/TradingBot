def main() -> int:
    args = parse_args()
    args.tickers = [t.upper() for t in args.tickers]
    args.full_workers = worker_policy.clamp_workers(args.full_workers)
    started_at = time.perf_counter()
    run_name = args.name or f"tournament_{args.start}_{args.end}_{time.strftime('%Y%m%d_%H%M%S')}"
    run_dir = os.path.join(args.out_dir, _safe_name(run_name))
    os.makedirs(run_dir, exist_ok=True)

    variants = list(slow_lab.VARIANTS)
    if args.extra_elite_variants:
        variants.extend(fast_lab.extra_elite_variants(args.extra_elite_variants, args.extra_seed))

    extra_paths = [args.source_csv, *list(args.baseline_scoring_profile or [])]
    if args.entry_gate_json:
        extra_paths.append(args.entry_gate_json)
    fingerprints = tournament_safety.run_fingerprint(args, extra_paths=extra_paths)
    source_rows = _read_csv(args.source_csv)
    lab_results, lab_variants = _lab_stage(args, variants, source_rows)
    lab_results = tournament_safety.enrich_lab_results(lab_results)

    rows_by_day = _load_decision_rows(args)
    baseline_results = _decision_baselines(args, rows_by_day)
    decision_results = _decision_stage(args, lab_variants, rows_by_day)
    decision_results = tournament_safety.enrich_decision_results(
        decision_results,
        lab_results,
        min_trades=args.min_trades,
        max_trades=args.max_trades,
    )
    decision_variants_by_name = {variant.name: variant for variant in lab_variants}
    if args.disable_diverse_finalists:
        selected_decision_rows = decision_results[:max(0, args.decision_top_n)]
    else:
        selected_decision_rows = tournament_safety.select_diverse_finalists(
            decision_results,
            max(0, args.decision_top_n),
            per_family=max(1, args.diverse_finalists_per_family),
        )
    finalist_variants = [decision_variants_by_name[row['variant']] for row in selected_decision_rows]

    full_replay_results = []
    if not args.skip_full_replay and args.full_top_n > 0:
        full_replay_results = _full_replay_stage(args, finalist_variants[:args.full_top_n], run_dir)
        full_replay_results = tournament_safety.enrich_full_results(full_replay_results, decision_results)

    elapsed = round(time.perf_counter() - started_at, 3)
    payload = {
        'schema_version': 2,
        'run_name': run_name,
        'elapsed_seconds': elapsed,
        'config': vars(args),
        'fingerprints': fingerprints,
        'counts': {
            'variants_total': len(variants),
            'lab_shortlist': len(lab_variants),
            'decision_results': len(decision_results),
            'selected_decision_finalists': len(finalist_variants),
            'full_replay_results': len(full_replay_results),
            'baseline_results': len(baseline_results),
        },
        'method_notes': [
            'lab_results are a hypothetical proxy using mechanical inverse P/L for side flips.',
            'decision_results use captured decision points with precomputed LONG/SHORT paths, open-position blocking, cooldown, and compounding.',
            'full_replay_results are the highest-fidelity stage and should be treated as the backtest verdict.',
            'composite_score penalizes train/test instability, worst-day loss, concentration, and automatic selection flags.',
            'family_id groups near-related weight signatures so finalist selection can avoid replaying many duplicates.',
        ],
        'lab_results': lab_results,
        'baseline_results': baseline_results,
        'decision_results': decision_results,
        'selected_decision_finalists': selected_decision_rows,
        'full_replay_results': full_replay_results,
    }
    out_path = os.path.join(run_dir, 'tournament_summary.json')
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(payload, f, indent=2, sort_keys=True)
    registry_path = None
    if not args.no_registry:
        registry_path = tournament_safety.append_registry(
            tournament_safety.registry_rows(payload, out_path),
            args.registry_path,
        )

    print(json.dumps({
        'out': out_path,
        'registry': registry_path,
        'elapsed_seconds': elapsed,
        'counts': payload['counts'],
        'top_lab': lab_results[0] if lab_results else None,
        'top_decision': decision_results[0] if decision_results else None,
        'top_full_replay': full_replay_results[0] if full_replay_results else None,
    }, indent=2))
    return 0


